import { Copy, KeyRound } from "lucide-react";
import { useState } from "react";

import { ReferenceEditor } from "@/components/crud";
import { useNotice } from "@/components/feedback";
import {
  AlertDialog,
  AlertDialogAction,
  AlertDialogContent,
  AlertDialogDescription,
  AlertDialogFooter,
  AlertDialogHeader,
  AlertDialogTitle,
  Badge,
  Button,
  Input,
} from "@/components/ui";
import {
  ADMIN_ROLES,
  authService,
  rolePermissions,
  usePermission,
  type AdminUser,
  type CreatedStaff,
  type StaffDraft,
} from "@/features/auth";
import { useFormatters, useTranslation } from "@/i18n";
import { PERMISSIONS } from "@/types";

const EMPTY: StaffDraft = { name: "", email: "", role: "viewer" };

/**
 * The generated password of an account just added. The API returns it once
 * and never again, so this dialog is the only place it can be read — it does
 * not close on an outside click, only on "Done" or Escape.
 */
function TemporaryPasswordDialog({ staff, onClose }: { staff: CreatedStaff | null; onClose: () => void }) {
  const { t } = useTranslation();
  const notice = useNotice();
  const password = staff?.temporaryPassword ?? "";

  const copy = async () => {
    try {
      await navigator.clipboard.writeText(password);
      notice.success(t("team.tempPassword.copied"));
    } catch {
      notice.error(t("team.tempPassword.copyFailed"));
    }
  };

  return (
    <AlertDialog open={staff !== null} onOpenChange={(open) => !open && onClose()}>
      <AlertDialogContent>
        <AlertDialogHeader>
          <div className="mb-1 flex size-10 items-center justify-center rounded-full bg-primary/10 text-primary">
            <KeyRound className="size-5" aria-hidden="true" />
          </div>
          <AlertDialogTitle>{t("team.tempPassword.title")}</AlertDialogTitle>
          <AlertDialogDescription>
            {t("team.tempPassword.body", { name: staff?.name ?? "", email: staff?.email ?? "" })}
          </AlertDialogDescription>
        </AlertDialogHeader>
        <div className="flex items-center gap-2">
          <Input
            readOnly
            dir="ltr"
            aria-label={t("team.tempPassword.title")}
            className="font-mono"
            value={password}
            onFocus={(event) => event.currentTarget.select()}
          />
          <Button type="button" variant="outline" onClick={() => void copy()}>
            <Copy aria-hidden="true" />
            {t("team.tempPassword.copy")}
          </Button>
        </div>
        <AlertDialogFooter>
          <AlertDialogAction>{t("team.tempPassword.done")}</AlertDialogAction>
        </AlertDialogFooter>
      </AlertDialogContent>
    </AlertDialog>
  );
}

/**
 * SETTINGS → TEAM. Who can sign in to the admin, and with which role.
 *
 * The role decides the permissions (see `features/auth/permissions.ts`); the
 * table shows how many each role carries so an owner can see what they are
 * granting. The API refuses to remove your own account or the last owner —
 * a team with no owner could never manage staff again. The table is paged and
 * searched by the API (`listStaffPage`).
 *
 * A new account gets a password generated by the API, returned once; it is
 * shown to whoever added the account right after the save.
 */
export function TeamRoute() {
  const { t } = useTranslation();
  const { number } = useFormatters();
  const canWrite = usePermission("settings:write");
  const [issued, setIssued] = useState<CreatedStaff | null>(null);
  const roleLabel = (role: AdminUser["role"]) => t(`team.role.${role}`);

  return (
    <>
      <ReferenceEditor<AdminUser, StaffDraft>
        title={t("team.title")}
        description={t("team.description")}
        noun={t("team.noun")}
        load={(query) => authService.listStaffPage(query)}
        nameOf={(user) => user.name}
        canWrite={canWrite}
        columns={[
          { key: "name", header: t("field.name"), render: (user) => user.name },
          { key: "email", header: t("field.email"), render: (user) => <span dir="ltr">{user.email}</span> },
          { key: "role", header: t("team.roleLabel"), render: (user) => <Badge variant="secondary">{roleLabel(user.role)}</Badge> },
          {
            key: "permissions",
            header: t("team.permissions"),
            align: "end",
            render: (user) => `${number(rolePermissions[user.role].length)} / ${number(PERMISSIONS.length)}`,
          },
        ]}
        fields={[
          { kind: "text", key: "name", label: t("field.name"), required: true },
          { kind: "text", key: "email", label: t("field.email"), required: true, hint: t("team.emailHint") },
          {
            kind: "select",
            key: "role",
            label: t("team.roleLabel"),
            hint: t("team.roleHint"),
            options: ADMIN_ROLES.map((role) => ({ value: role, label: roleLabel(role) })),
          },
        ]}
        empty={EMPTY}
        toDraft={({ id: _id, ...draft }) => draft}
        create={async (draft) => {
          const created = await authService.createStaff(draft);
          if (created.temporaryPassword) setIssued(created);
        }}
        update={(id, draft) => authService.updateStaff(id, draft)}
        remove={(id) => authService.deleteStaff(id)}
      />
      <TemporaryPasswordDialog staff={issued} onClose={() => setIssued(null)} />
    </>
  );
}
